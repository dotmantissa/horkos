#!/usr/bin/env python3
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
output = root / 'app/lib/abis.ts'
output.parent.mkdir(parents=True, exist_ok=True)
parts = ['// Generated by scripts/export-abis.py from verified Foundry artifacts.\n']
for name in ['TestCoin', 'MockFeeHook', 'OathVault', 'HorkosRegistry', 'HorkosLens']:
    artifact = json.loads((root / f'contracts/out/{name}.sol/{name}.json').read_text())
    parts.append(f'export const {name[0].lower()+name[1:]}Abi = '+json.dumps(artifact['abi'],indent=2)+' as const;\n')
output.write_text('\n'.join(parts))
print('Exported contract ABIs to app/lib/abis.ts')
